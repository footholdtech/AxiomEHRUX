#!/usr/bin/env python3
"""Build the prototype into self-contained HTML.

Writes the SAME fully-inlined document to two names:

  index.html                     the one you open while working
  AxiomEHR-Discharge-Plan.html   the one you send to somebody

Both are complete on their own — CSS, fonts as data: URIs, icons, reference
data, React, ReactDOM, Babel and the app source, all inlined. Nothing is
fetched, so there is no way to break them by moving the file, and no way for
Safari's file:// subresource restrictions to bite.

An earlier version kept a lightweight index.html that loaded siblings. It
failed twice in the field — once as "Cannot read properties of undefined" when
assets/refdata.js didn't load, once as "Babel is not defined" when vendor/ was
out of reach. There is no such thing as a file that only ever gets opened the
intended way, so both outputs are now self-contained.

Re-run after any change under src/, styles/, assets/ or vendor/.
"""
import base64, mimetypes, pathlib, re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
OUTPUTS = [ROOT / "index.html", ROOT / "AxiomEHR-Discharge-Plan.html"]

CSS_BLOCKING = ["styles/tokens.css", "styles/app.css", "styles/discharge.css"]
CSS_DEFERRED = "styles/fonts.css"   # ~1.4 MB of base64 faces; never render-blocking
JS = ["assets/fluent-icons.js", "assets/ds-icons.js", "assets/refdata.js",
      "vendor/react.production.min.js", "vendor/react-dom.production.min.js", "vendor/babel.min.js"]

FONT_MIME = {".ttf": "font/ttf", ".otf": "font/otf", ".woff": "font/woff", ".woff2": "font/woff2"}


def data_uri(path: pathlib.Path) -> str:
    mime = FONT_MIME.get(path.suffix.lower()) or mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    return f"data:{mime};base64,{base64.b64encode(path.read_bytes()).decode()}"


def inline_css_urls(css: str, base: pathlib.Path) -> str:
    """Replace url('../assets/fonts/X.ttf') with that font's data: URI."""
    def sub(m):
        ref = m.group(2).strip()
        if ref.startswith(("data:", "http:", "https:")):
            return m.group(0)
        target = (base / ref).resolve()
        if not target.exists():
            raise SystemExit(f"css references a missing file: {ref}")
        return f"url('{data_uri(target)}')"
    return re.sub(r"url\((['\"]?)([^'\")]+)\1\)", sub, css)


def esc(js: str) -> str:
    """Make arbitrary JS safe to sit inside a <script> element.

    Two sequences can end or derail the element's raw-text parsing: `</script`
    closes it, and `<!--` switches the tokenizer into "script data escaped"
    state, where a later `<script` can make the real `</script>` get swallowed.
    Both are neutralised with a backslash, which JS treats as an identity
    escape inside the string and regex literals where these actually occur.
    """
    js = re.sub(r"</(script)", r"<\\/\1", js, flags=re.I)
    js = js.replace("<!--", "<\\!--")
    return js


def build() -> str:
    app = "\n".join(
        f"/* ==================== {f.name} ==================== */\n{f.read_text().rstrip()}\n"
        for f in sorted((ROOT / "src").glob("*.jsx"))
    )

    parts = ["<!doctype html>",
             '<html lang="en" data-theme="purple" data-mode="light">',
             "<head>", '<meta charset="UTF-8" />',
             '<meta name="viewport" content="width=device-width, initial-scale=1.0" />',
             "<title>AxiomEHR — Discharge Plan · interaction-design prototype</title>",
             "<!-- Self-contained: generated by tools/build.py from src/, styles/, assets/",
             "     and vendor/. Do not hand-edit; edit the sources and re-run the build. -->"]

    # Only the small stylesheets block rendering. The font faces carry ~1.4 MB
    # of base64 between them; in a <style> in the head they hold up first paint
    # for most of a second, which is what made the page look blank on open.
    for rel in CSS_BLOCKING:
        p = ROOT / rel
        parts.append(f"<!-- {rel} -->\n<style>\n{inline_css_urls(p.read_text(), p.parent)}\n</style>")

    parts += ["</head>", "<body>", SPLASH]

    parts.append(f"<script>window.__AXIOM_LOGO = {data_uri(ROOT / 'assets' / 'radicle-health.svg')!r};</script>")

    # Everything heavy rides in text/plain blocks. The parser only scans them as
    # raw text, so it reaches the end of the document — and paints the splash —
    # before any of this is compiled or run.
    fonts = ROOT / CSS_DEFERRED
    parts.append('<style type="text/plain" id="font-css">\n'
                 + inline_css_urls(fonts.read_text(), fonts.parent).replace("</style", "<\\/style")
                 + "\n</style>")
    for rel in JS:
        p = ROOT / rel
        parts.append(f'<!-- {rel} -->\n<script type="text/plain" class="deferred-js">\n{esc(p.read_text())}\n</script>')

    parts.append('<script type="text/plain" id="app-code">\n' + esc(app) + "\n</script>")
    parts.append(BOOTSTRAP)
    parts += ["</body>", "</html>"]
    return "\n".join(parts) + "\n"


SPLASH = """<div id="root"><div class="boot">
  <div class="boot-mark"></div>
  <div class="boot-name">AxiomEHR</div>
  <div class="boot-sub">Discharge Plan · interaction-design prototype</div>
  <div class="boot-bar"><span></span></div>
</div></div>"""

BOOTSTRAP = """<script>
(function () {
  var root = document.getElementById('root');
  function fatal(title, body) {
    root.innerHTML = '<div style="max-width:620px;margin:12vh auto;font:14px/1.6 system-ui,sans-serif;color:#36435c">'
      + '<h1 style="font-size:20px;margin:0 0 8px">' + title + '</h1>' + body + '</div>';
  }

  function start() {
    // Font faces first: they are the largest payload and the least urgent, and
    // font-display:swap means text is already on screen in a fallback.
    var fontCss = document.getElementById('font-css');
    if (fontCss) {
      var s = document.createElement('style');
      s.textContent = fontCss.textContent;
      document.head.appendChild(s);
      fontCss.remove();
    }

    // React, ReactDOM, Babel, icons and reference data.
    var blocks = document.querySelectorAll('script.deferred-js');
    for (var i = 0; i < blocks.length; i++) {
      try { (0, eval)(blocks[i].textContent); }
      catch (e) { fatal('The prototype failed to start', '<p>A bundled library did not evaluate: ' + e.message + '</p>'); throw e; }
    }

    // Everything is inlined, so a missing global means the file itself is
    // truncated — say that, rather than throwing from deep inside the app.
    var missing = [];
    if (typeof React === 'undefined') missing.push('React');
    if (typeof ReactDOM === 'undefined') missing.push('ReactDOM');
    if (typeof Babel === 'undefined') missing.push('Babel');
    if (!window.REFDATA || !window.REFDATA.clients) missing.push('reference data');
    if (missing.length) {
      fatal('This file is incomplete',
        '<p>' + missing.join(', ') + ' did not load. Everything this prototype needs is inlined in '
        + 'a single HTML file, so this usually means the copy you opened was truncated in transit '
        + '(email and chat clients sometimes clip large attachments).</p>'
        + '<p>Ask for a fresh copy of <b>AxiomEHR-Discharge-Plan.html</b> — it should be about 4.9 MB.</p>');
      return;
    }

    try {
      var src = document.getElementById('app-code').textContent;
      (0, eval)(Babel.transform(src, { presets: [['react', { runtime: 'classic' }]], filename: 'app.jsx' }).code);
    } catch (e) {
      if (window.__AXIOM_FATAL) throw e;   // the app wrote its own message
      fatal('The prototype failed to start',
        '<pre style="font:13px/1.5 ui-monospace,monospace;color:#b3261e;white-space:pre-wrap">'
        + String(e && e.message || e).replace(/[<>&]/g, function (c) {
            return { '<': '&lt;', '>': '&gt;', '&': '&amp;' }[c]; }) + '</pre>');
      throw e;
    }
  }

  // Yield once so the splash is actually on screen before we spend ~700ms
  // parsing Babel and compiling the app; without a yield point the browser
  // stays blank for the whole of it.
  //
  // Two triggers, whichever fires first. rAF gives the cleanest result in a
  // visible tab — but it does NOT fire in a background or throttled tab, so it
  // can never be the only path to starting the app, or the page sits on the
  // splash forever in an unfocused window.
  var started = false;
  function go() { if (started) return; started = true; start(); }
  requestAnimationFrame(function () { requestAnimationFrame(function () { setTimeout(go, 0); }); });
  setTimeout(go, 150);
})();
</script>"""


html = build()
for out in OUTPUTS:
    out.write_text(html)
print(f"built {len(html) / 1e6:.1f} MB → " + ", ".join(o.name for o in OUTPUTS))
print("both are self-contained: no siblings, no network, no CDN")
