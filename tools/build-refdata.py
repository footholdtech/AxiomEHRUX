#!/usr/bin/env python3
"""Inline fixtures/reference-data/*.json into assets/refdata.js.

The prototype must open straight from file:// (double-click), and browsers block
fetch() on file:// URLs — so the data ships as a plain <script> that assigns
window.REFDATA rather than something the app fetches. Re-run after editing any
fixture.
"""
import json, pathlib

HERE = pathlib.Path(__file__).resolve().parent
RD = HERE.parent / "fixtures" / "reference-data"
OUT = HERE.parent / "assets" / "refdata.js"

# key in window.REFDATA -> fixture filename
FILES = {
    "clients": "clients.json", "staff": "staff.json", "roles": "roles.json",
    "programs": "programs.json", "sites": "sites_locations.json", "funding": "funding.json",
    "diagnoses": "diagnosis_codes.json", "problems": "problem_list.json",
    "attributes": "client_attributes.json", "noteTypes": "note_types.json",
    "assessments": "assessments.json", "medications": "medications.json",
    "allergies": "allergies.json", "vitals": "vitals.json",
    "prescriptions": "prescriptions.json", "payors": "payor_assignments.json",
    "appointments": "appointments.json", "notifications": "notifications.json",
    "clientDiagnoses": "client_diagnoses.json", "clientProblems": "client_problems.json",
    # Home's Messenger module reads these; the fixtures existed but were never shipped.
    "staffMessages": "messages_staff_to_staff.json",
    "clientMessages": "messages_staff_to_client.json",
    # Client header clinical quick views — generated by tools/build-header-fixtures.py.
    "formularyAdditions": "formulary_additions.json",
    "medHistory": "medication_history.json",
    "immunizations": "immunizations.json",
    "injections": "injections.json",
    "vitalsHistory": "vitals_history.json",
    "assessmentForms": "assessment_forms.json",
    "assessmentAdmins": "assessment_administrations.json",
    "clientNotes": "client_notes.json",
    "notifCenter": "notification_center.json",
    "servicePlans": "service_plans.json",
}

data = {}
for key, fname in FILES.items():
    path = RD / fname
    if not path.exists():
        raise SystemExit(f"missing fixture: {fname}")
    blob = json.loads(path.read_text())
    data[key] = blob["records"] if isinstance(blob, dict) and "records" in blob else blob

OUT.write_text(
    "/* AUTO-GENERATED by tools/build-refdata.py from fixtures/reference-data/*.json.\n"
    "   100% synthetic — no real PHI. Do not hand-edit. */\n"
    "window.REFDATA = " + json.dumps(data, separators=(",", ":")) + ";\n"
)
print(f"{OUT.name}: {len(data)} tables, {OUT.stat().st_size:,} bytes")
